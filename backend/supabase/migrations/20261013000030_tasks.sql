-- ---------------------------------------------------------------------------
-- Migration 30: concierge-assigned tasks.
--
-- The brief asks for one set of task records shared by two dashboards: the
-- concierge writes them, the employee works them. So this is a single table
-- with a single status machine - not a "task" row on the concierge side and a
-- copy on the employee side. Two copies is how a task gets marked complete in
-- one place and stays open in the other.
--
-- ## Ownership is a column, and the API is what enforces it
--
-- `employee_id` is who the task is FOR. The rule "an employee may only touch
-- their own tasks" is checked in the service layer against the caller's
-- `employees` row, because the caller's identity is a token the database
-- cannot see. RLS is switched on and the table is granted to service_role
-- alone, so the API is the only way in.
--
-- ## Why the status machine lives in a trigger
--
-- The same reason migration 11 put the booking status machine in one: a
-- transition rule written in the API is a rule that any other writer - a
-- script, a future endpoint, a psql session - can walk straight past. Putting
-- it on the table means an illegal move is impossible, not merely discouraged.
-- The API's copy of the map exists only to render the right buttons.
--
--   PENDING     -> IN_PROGRESS, COMPLETED, CANCELLED
--   IN_PROGRESS -> PENDING, COMPLETED, CANCELLED
--   COMPLETED   -> PENDING        (re-open: the work was not actually done)
--   CANCELLED   -> PENDING        (re-instate)
--
-- COMPLETED and CANCELLED are otherwise terminal. Re-opening clears
-- `completed_at`, so the row never claims a completion it no longer has.
-- ---------------------------------------------------------------------------

-- ---------------------------------------------------------------------------
-- 1. Types.
-- ---------------------------------------------------------------------------
do $$
begin
  if not exists (select 1 from pg_type where typname = 'task_priority') then
    create type public.task_priority as enum ('LOW', 'MEDIUM', 'HIGH', 'URGENT');
  end if;
  if not exists (select 1 from pg_type where typname = 'task_status') then
    create type public.task_status as enum ('PENDING', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED');
  end if;
end $$;

comment on type public.task_priority is 'How urgent a task is. Ordering is the enum order: LOW < MEDIUM < HIGH < URGENT.';
comment on type public.task_status is 'PENDING -> IN_PROGRESS -> COMPLETED, with CANCELLED reachable from either open state. Enforced by trigger.';

-- ---------------------------------------------------------------------------
-- 2. The table.
-- ---------------------------------------------------------------------------
create table if not exists public.tasks (
  id          uuid primary key default gen_random_uuid(),
  -- A small human-readable id, because "Task ID" in the UI should be something
  -- a person can say out loud. The uuid stays the real key.
  number      bigint generated by default as identity,
  title       text not null,
  description text,
  employee_id uuid not null references public.employees (id) on delete cascade,
  created_by  uuid references public.profiles (id) on delete set null,
  priority    public.task_priority not null default 'MEDIUM',
  status      public.task_status   not null default 'PENDING',
  due_at      timestamptz,
  instructions text,
  completion_notes text,
  completed_at timestamptz,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),

  constraint tasks_title_len       check (length(btrim(title)) between 1 and 160),
  constraint tasks_description_len check (description      is null or length(description)      <= 2000),
  constraint tasks_instructions_len check (instructions    is null or length(instructions)     <= 2000),
  constraint tasks_notes_len       check (completion_notes is null or length(completion_notes) <= 2000),
  -- A task cannot claim to be finished without saying when.
  constraint tasks_completed_at_consistent
    check ((status = 'COMPLETED') = (completed_at is not null)),
  constraint tasks_number_key unique (number)
);

comment on table public.tasks is
  'Tasks a concierge assigns to an employee. One record, read by both dashboards. Status transitions are enforced by trigger.';

create index if not exists tasks_employee_status_idx on public.tasks (employee_id, status, due_at);
create index if not exists tasks_open_idx on public.tasks (due_at) where status in ('PENDING', 'IN_PROGRESS');

drop trigger if exists trg_tasks_updated_at on public.tasks;
create trigger trg_tasks_updated_at
  before update on public.tasks
  for each row execute function public.set_updated_at();

-- ---------------------------------------------------------------------------
-- 3. The status machine.
-- ---------------------------------------------------------------------------
create or replace function public.enforce_task_status_transition()
returns trigger
language plpgsql
as $function$
declare
  v_allowed public.task_status[];
begin
  if new.status = old.status then
    return new;
  end if;

  v_allowed := case old.status
    when 'PENDING'     then array['IN_PROGRESS', 'COMPLETED', 'CANCELLED']::public.task_status[]
    when 'IN_PROGRESS' then array['PENDING', 'COMPLETED', 'CANCELLED']::public.task_status[]
    when 'COMPLETED'   then array['PENDING']::public.task_status[]
    when 'CANCELLED'   then array['PENDING']::public.task_status[]
  end;

  if not (new.status = any (v_allowed)) then
    raise exception 'TASK_STATUS_TRANSITION: % -> % is not allowed', old.status, new.status
      using errcode = 'P0001';
  end if;

  -- Keep `completed_at` in step with the status, so the two can never disagree.
  if new.status = 'COMPLETED' then
    new.completed_at := coalesce(new.completed_at, now());
  else
    new.completed_at := null;
  end if;

  return new;
end;
$function$;

comment on function public.enforce_task_status_transition() is
  'The task status machine. Raises TASK_STATUS_TRANSITION for an illegal move.';

drop trigger if exists trg_tasks_status_transition on public.tasks;
create trigger trg_tasks_status_transition
  before update of status on public.tasks
  for each row execute function public.enforce_task_status_transition();

-- ---------------------------------------------------------------------------
-- 4. The read view.
--
-- The assignee's name and who assigned it, so a list of tasks does not need
-- one extra query per row to be readable.
-- ---------------------------------------------------------------------------
create or replace view public.v_task_detail as
select
  t.id,
  t.number,
  t.title,
  t.description,
  t.employee_id,
  e.full_name             as employee_name,
  t.created_by,
  coalesce(p.full_name, p2.full_name) as created_by_name,
  t.priority,
  t.status,
  t.due_at,
  t.instructions,
  t.completion_notes,
  t.completed_at,
  t.created_at,
  t.updated_at,
  -- Overdue is a fact about the clock, computed here so the employee's list and
  -- the concierge's board agree on which tasks are late.
  (t.due_at is not null and t.due_at < now() and t.status in ('PENDING', 'IN_PROGRESS')) as is_overdue
from public.tasks t
join public.employees e on e.id = t.employee_id
left join public.profiles p  on p.id  = t.created_by
-- `created_by` may point at a profile that has since been removed; the
-- employee record is the fallback attribution.
left join public.employees p2 on p2.profile_id = t.created_by;

comment on view public.v_task_detail is
  'Tasks joined to the assignee and the assigner, with an is_overdue flag.';

-- ---------------------------------------------------------------------------
-- 5. Locking it down.
-- ---------------------------------------------------------------------------
alter table public.tasks enable row level security;

revoke all on public.tasks from anon, authenticated;
grant all on public.tasks to service_role;

-- The identity sequence is separate from the table's grants.
revoke all on sequence public.tasks_number_seq from anon, authenticated;
grant usage, select on sequence public.tasks_number_seq to service_role;

alter view public.v_task_detail set (security_invoker = on);
revoke all on public.v_task_detail from anon, authenticated;
grant select on public.v_task_detail to service_role;

revoke execute on function public.enforce_task_status_transition() from public, anon, authenticated;
grant execute on function public.enforce_task_status_transition() to service_role;

-- ---------------------------------------------------------------------------
-- 6. Self-checks.
-- ---------------------------------------------------------------------------
do $$
declare
  v_count integer;
begin
  if not exists (select 1 from pg_type where typname = 'task_priority') then
    raise exception 'migration 30: task_priority type was not created';
  end if;
  if not exists (select 1 from pg_type where typname = 'task_status') then
    raise exception 'migration 30: task_status type was not created';
  end if;

  if not exists (
    select 1 from pg_trigger
     where tgrelid = 'public.tasks'::regclass and tgname = 'trg_tasks_status_transition'
  ) then
    raise exception 'migration 30: the status-transition trigger is missing';
  end if;

  if not (select relrowsecurity from pg_class where oid = 'public.tasks'::regclass) then
    raise exception 'migration 30: RLS is not enabled on tasks';
  end if;

  if has_table_privilege('anon', 'public.tasks', 'SELECT')
     or has_table_privilege('authenticated', 'public.tasks', 'SELECT') then
    raise exception 'migration 30: tasks is readable by anon/authenticated';
  end if;

  if has_table_privilege('anon', 'public.v_task_detail', 'SELECT')
     or has_table_privilege('authenticated', 'public.v_task_detail', 'SELECT') then
    raise exception 'migration 30: v_task_detail is readable by anon/authenticated';
  end if;

  if not exists (select 1 from pg_views where schemaname = 'public' and viewname = 'v_task_detail') then
    raise exception 'migration 30: v_task_detail was not created';
  end if;
end $$;

-- Behavioural check: the status machine must refuse an illegal move and must
-- keep completed_at in step. Rolled back - the raise at the end is deliberate.
do $$
declare
  v_employee uuid;
  v_task     uuid;
  v_number   bigint;
begin
  select id into v_employee from public.employees where is_active order by id limit 1;
  if v_employee is null then
    raise notice 'migration 30: no active employees - skipping the behavioural check';
    return;
  end if;

  begin
    insert into public.tasks (title, description, employee_id, priority, due_at)
    values ('Migration 30 probe', 'Disposable.', v_employee, 'HIGH', now() + interval '1 day')
    returning id, number into v_task, v_number;

    if v_number is null then
      raise exception 'migration 30: a task was created without a human-readable number';
    end if;

    -- PENDING -> IN_PROGRESS -> COMPLETED, with completed_at written for us.
    update public.tasks set status = 'IN_PROGRESS' where id = v_task;
    update public.tasks set status = 'COMPLETED'   where id = v_task;

    if (select completed_at from public.tasks where id = v_task) is null then
      raise exception 'migration 30: COMPLETED did not set completed_at';
    end if;

    -- Re-opening must clear it again, or the row claims a completion it lost.
    update public.tasks set status = 'PENDING' where id = v_task;
    if (select completed_at from public.tasks where id = v_task) is not null then
      raise exception 'migration 30: re-opening a task left completed_at set';
    end if;

    -- PENDING -> CANCELLED is allowed; CANCELLED -> IN_PROGRESS is not.
    update public.tasks set status = 'CANCELLED' where id = v_task;
    begin
      update public.tasks set status = 'IN_PROGRESS' where id = v_task;
      raise exception 'migration 30: CANCELLED -> IN_PROGRESS was accepted';
    exception
      when others then
        if sqlerrm not like 'TASK_STATUS_TRANSITION%' then
          raise;
        end if;
    end;

    -- A blank title must be refused.
    begin
      insert into public.tasks (title, employee_id) values ('   ', v_employee);
      raise exception 'migration 30: a blank title was accepted';
    exception
      when check_violation then null;
    end;

    raise exception 'ROLLBACK_TASK_PROBE';
  exception
    when others then
      if sqlerrm = 'ROLLBACK_TASK_PROBE' then
        raise notice 'migration 30: behavioural check passed';
      else
        raise;
      end if;
  end;
end $$;
